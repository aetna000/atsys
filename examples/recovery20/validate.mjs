import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { DatabaseSync } from 'node:sqlite';
const read=path=>JSON.parse(readFileSync(path,'utf8'));
const state=read('state.json');
const result=read('result.json');
const events=readFileSync('journal.jsonl','utf8').trim().split('\n').map(JSON.parse);
assert.equal(result.kind,'controlled-local-memory-fixture-not-dolphinbench');
assert.equal(state.completed,20);assert.equal(state.faultInjected,true);
assert.equal(result.results.length,20);
assert.deepEqual(result.results.map(r=>r.task_id),Array.from({length:20},(_,i)=>i+1));
assert.ok(result.results.every(r=>r.actual_id===r.task_id && r.passed===1));
assert.equal(events.filter(e=>e.type==='task.completed').length,20,'No duplicate task executions');
assert.deepEqual(events.filter(e=>e.type==='task.completed').map(e=>e.task_id),Array.from({length:20},(_,i)=>i+1));
assert.equal(events.filter(e=>e.type==='fault.injected').length,1);
assert.equal(events.find(e=>e.type==='fault.injected').afterTask,5);
assert.equal(read('engine.json').enabled,true);
assert.equal(read('repair-receipt.json').action,'restore_engine_config');
const db=new DatabaseSync('fixture.sqlite',{readOnly:true});
assert.equal(db.prepare('SELECT count(*) AS n FROM results').get().n,20);
db.close();
console.log('ACCEPTED: 20/20 controlled local retrieval tasks; injected fault at5 repaired; first5 not replayed. Not a DolphinBench score.');
